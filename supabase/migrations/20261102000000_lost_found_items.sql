-- ════════════════════════════════════════════════════════════════════════
-- M2 — Lost & Found Item Management
--   lost_items · lost_item_private · found_items · item_images · lookups
--
-- Reports are created through the create-lost-item / create-found-item Edge
-- Functions (they HMAC identifiers and issue the claim credential), so
-- clients get no direct INSERT on the item tables. Owners may edit their
-- own reports; status transitions are guarded by triggers.
-- ════════════════════════════════════════════════════════════════════════

-- ─── Ownership / visibility helpers (SECURITY DEFINER: used by RLS and
--     storage policies without recursing through RLS) ────────────────────

create or replace function public.owns_lost_item(item_id uuid)
returns boolean
language sql stable security definer set search_path = public
as $$
  select exists (select 1 from public.lost_items where id = item_id and user_id = auth.uid());
$$;

create or replace function public.owns_found_item(item_id uuid)
returns boolean
language sql stable security definer set search_path = public
as $$
  select exists (select 1 from public.found_items where id = item_id and finder_id = auth.uid());
$$;

-- A found item is visible to its finder, admins, and owners of a lost item
-- that the matching engine paired with it (needed for the match screen).
create or replace function public.can_view_found_item(item_id uuid)
returns boolean
language sql stable security definer set search_path = public
as $$
  select public.is_admin()
    or exists (select 1 from public.found_items where id = item_id and finder_id = auth.uid())
    or exists (
      select 1
      from public.match_candidates mc
      join public.lost_items li on li.id = mc.lost_item_id
      where mc.found_item_id = item_id and li.user_id = auth.uid()
    );
$$;

-- ─── lost_items ─────────────────────────────────────────────────────────

create policy "Lost items: owner or admin can read"
  on public.lost_items for select
  using (user_id = auth.uid() or public.is_admin());

create policy "Lost items: owner or admin can update"
  on public.lost_items for update
  using (user_id = auth.uid() or public.is_admin())
  with check (user_id = auth.uid() or public.is_admin());

revoke insert, update, delete on public.lost_items from anon, authenticated;
grant update (category_id, location_id, title, description, brand, model, color, date_lost, status)
  on public.lost_items to authenticated;

-- Owners may edit only while the report is active, and may only move the
-- status to CANCELLED. Admins and server-side code are unrestricted.
create or replace function public.guard_lost_item_update()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if current_user not in ('authenticated', 'anon') or public.is_admin() then
    return new;
  end if;

  if old.status not in ('LOST', 'MATCHED') then
    raise exception 'This report can no longer be changed (status %).', old.status
      using errcode = '42501';
  end if;

  if new.status is distinct from old.status and new.status <> 'CANCELLED' then
    raise exception 'You can only cancel a report; other status changes are made by FoundIT.'
      using errcode = '42501';
  end if;

  -- Descriptive edits invalidate the stored embedding (re-generated by M3).
  if (new.title, new.description) is distinct from (old.title, old.description) then
    new.description_embedding := null;
  end if;

  return new;
end;
$$;

create trigger lost_items_guard_update
  before update on public.lost_items
  for each row execute function public.guard_lost_item_update();

-- ─── lost_item_private (private ownership information) ──────────────────

create policy "Private info: owner or admin can read"
  on public.lost_item_private for select
  using (public.owns_lost_item(lost_item_id) or public.is_admin());

create policy "Private info: owner can update while report is active"
  on public.lost_item_private for update
  using (
    public.owns_lost_item(lost_item_id)
    and exists (select 1 from public.lost_items li
                where li.id = lost_item_id and li.status in ('LOST', 'MATCHED'))
  );

revoke insert, update, delete on public.lost_item_private from anon, authenticated;
grant update (private_ownership_info) on public.lost_item_private to authenticated;

-- ─── found_items ────────────────────────────────────────────────────────

create policy "Found items: finder, admin or matched owner can read"
  on public.found_items for select
  using (public.can_view_found_item(id));

create policy "Found items: finder or admin can update"
  on public.found_items for update
  using (finder_id = auth.uid() or public.is_admin())
  with check (finder_id = auth.uid() or public.is_admin());

revoke insert, update, delete on public.found_items from anon, authenticated;
grant update (category_id, location_id, title, description, brand, model, color,
              date_found, status, collection_point_id)
  on public.found_items to authenticated;

create or replace function public.guard_found_item_update()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if current_user not in ('authenticated', 'anon') or public.is_admin() then
    return new;
  end if;

  if new.status is distinct from old.status then
    raise exception 'Only FoundIT staff can change the status of a found report.'
      using errcode = '42501';
  end if;

  if old.status not in ('FOUND', 'IN_STORAGE', 'MATCHED') then
    raise exception 'This report can no longer be changed (status %).', old.status
      using errcode = '42501';
  end if;

  if (new.title, new.description) is distinct from (old.title, old.description) then
    new.description_embedding := null;
  end if;

  return new;
end;
$$;

create trigger found_items_guard_update
  before update on public.found_items
  for each row execute function public.guard_found_item_update();

-- ─── item_images ────────────────────────────────────────────────────────

create policy "Item images: readable with the item"
  on public.item_images for select
  using (
    (lost_item_id is not null and (public.owns_lost_item(lost_item_id) or public.is_admin()))
    or (found_item_id is not null and public.can_view_found_item(found_item_id))
  );

create policy "Item images: owner can attach to own item"
  on public.item_images for insert to authenticated
  with check (
    uploaded_by = auth.uid()
    and (
      (lost_item_id is not null
        and public.owns_lost_item(lost_item_id)
        and storage_path like 'lost/' || lost_item_id::text || '/%')
      or
      (found_item_id is not null
        and public.owns_found_item(found_item_id)
        and storage_path like 'found/' || found_item_id::text || '/%')
    )
  );

create policy "Item images: uploader or admin can delete"
  on public.item_images for delete
  using (uploaded_by = auth.uid() or public.is_admin());

revoke update on public.item_images from anon, authenticated;

-- At most 10 photos per report.
create or replace function public.limit_item_images()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if (select count(*) from public.item_images
      where lost_item_id is not distinct from new.lost_item_id
        and found_item_id is not distinct from new.found_item_id) >= 10 then
    raise exception 'A report can have at most 10 photos.' using errcode = '23514';
  end if;
  return new;
end;
$$;

create trigger item_images_limit
  before insert on public.item_images
  for each row execute function public.limit_item_images();

