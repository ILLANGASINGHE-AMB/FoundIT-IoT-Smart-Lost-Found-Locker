-- ─── Storage: item photos (private bucket) ──────────────────────────────
-- Paths: item-images/lost/{lost_item_id}/{file} · item-images/found/{found_item_id}/{file}
-- Bucket limits enforce type/size server-side (5 MB, JPEG/PNG/WebP).

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('item-images', 'item-images', false, 5242880,
        array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do nothing;

create or replace function public.item_object_access(object_name text, for_write boolean)
returns boolean
language plpgsql stable security definer set search_path = public
as $$
declare
  parts text[] := string_to_array(object_name, '/');
  item_id uuid;
begin
  if array_length(parts, 1) <> 3
     or parts[2] !~ '^[0-9a-fA-F-]{36}$' then
    return false;
  end if;
  item_id := parts[2]::uuid;

  if parts[1] = 'lost' then
    return public.owns_lost_item(item_id) or (not for_write and public.is_admin());
  elsif parts[1] = 'found' then
    if for_write then
      return public.owns_found_item(item_id);
    end if;
    return public.can_view_found_item(item_id);
  end if;
  return false;
end;
$$;

create policy "Item photos: read with item access"
  on storage.objects for select to authenticated
  using (bucket_id = 'item-images' and public.item_object_access(name, false));

create policy "Item photos: owners upload into their item folder"
  on storage.objects for insert to authenticated
  with check (bucket_id = 'item-images' and public.item_object_access(name, true));

create policy "Item photos: owners or admins delete"
  on storage.objects for delete to authenticated
  using (
    bucket_id = 'item-images'
    and (public.item_object_access(name, true) or public.is_admin())
  );
